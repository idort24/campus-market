-- 商品统计快照：按分类聚合当前 goods 的真实分布
DELETE FROM goods_stat;
INSERT INTO goods_stat (category_id, total_count, audit_pass_count, up_count, sold_count, stat_time)
SELECT
    g.category_id,
    COUNT(*),
    SUM(CASE WHEN g.audit_status = 'PASS' THEN 1 ELSE 0 END),
    SUM(CASE WHEN g.goods_status = 'ON_SHELF' THEN 1 ELSE 0 END),
    SUM(CASE WHEN g.goods_status = 'SOLD' THEN 1 ELSE 0 END),
    NOW()
FROM goods g
WHERE g.is_deleted = 0
GROUP BY g.category_id;

-- 自检
SELECT '商品总数' AS 指标, COUNT(*) AS 值 FROM goods WHERE is_deleted = 0
UNION ALL SELECT '上架中', COUNT(*) FROM goods WHERE goods_status = 'ON_SHELF' AND is_deleted = 0
UNION ALL SELECT '待审核', COUNT(*) FROM goods WHERE audit_status = 'PENDING' AND is_deleted = 0
UNION ALL SELECT '已售出', COUNT(*) FROM goods WHERE goods_status = 'SOLD' AND is_deleted = 0
UNION ALL SELECT '覆盖分类数', COUNT(DISTINCT category_id) FROM goods WHERE is_deleted = 0;
